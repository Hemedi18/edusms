from django.urls import path
from .views import (
    AccountDataExportView,
    AccountDeleteView,
    ChangePasswordView,
    CurrentUserProfileView,
    LoginView,
    LogoutView,
    MFADisableView,
    MFASetupView,
    MFAVerifyEnableView,
    PasswordResetConfirmView,
    PasswordResetRequestView,
    RefreshSessionView,
    RegisterView,
    ResendVerificationView,
    SessionListView,
    SessionRevokeView,
    VerifyEmailView,
)

urlpatterns = [
    path("register/", RegisterView.as_view(), name="auth-register"),
    path("login/", LoginView.as_view(), name="auth-login"),
    path("refresh/", RefreshSessionView.as_view(), name="auth-refresh"),
    path("logout/", LogoutView.as_view(), name="auth-logout"),
    path("me/", CurrentUserProfileView.as_view(), name="auth-me"),
    path("change-password/", ChangePasswordView.as_view(), name="auth-change-password"),
    path("verify-email/", VerifyEmailView.as_view(), name="auth-verify-email"),
    path("resend-verification/", ResendVerificationView.as_view(), name="auth-resend-verification"),
    path("password-reset/", PasswordResetRequestView.as_view(), name="auth-password-reset"),
    path("password-reset/confirm/", PasswordResetConfirmView.as_view(), name="auth-password-reset-confirm"),
    path("sessions/", SessionListView.as_view(), name="auth-sessions"),
    path("sessions/<uuid:pk>/revoke/", SessionRevokeView.as_view(), name="auth-session-revoke"),
    path("mfa/setup/", MFASetupView.as_view(), name="auth-mfa-setup"),
    path("mfa/verify/", MFAVerifyEnableView.as_view(), name="auth-mfa-verify"),
    path("mfa/disable/", MFADisableView.as_view(), name="auth-mfa-disable"),
    path("export/", AccountDataExportView.as_view(), name="auth-export"),
    path("delete-account/", AccountDeleteView.as_view(), name="auth-delete-account"),
]
